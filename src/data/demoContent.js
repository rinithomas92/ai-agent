/**
 * Returns a demo content pack containing a quote, caption, and hashtags.
 */
export function getDemoContent(categoryName = '', dayIndex = 0, excludeQuotes = []) {
  let cat = categoryName.toLowerCase().replace(/[^a-z]/g, '');
  const keys = Object.keys(demoQuotes);
  if (!demoQuotes[cat]) {
    const matchedKey = keys.find(k => cat.includes(k) || k.includes(cat));
    cat = matchedKey || 'motivation';
  }

  const quotes = demoQuotes[cat];
  const captions = demoCaptions[cat];

  // Try to find a quote not in excludeQuotes
  let selectedQuote = '';
  const availableQuotes = quotes.filter(q => !excludeQuotes.includes(q.toLowerCase()));
  if (availableQuotes.length > 0) {
    // Pick sequentially or randomly
    selectedQuote = availableQuotes[dayIndex % availableQuotes.length];
  } else {
    selectedQuote = buildDynamicDemoQuote(cat, Math.max(0, dayIndex - quotes.length), excludeQuotes);
  }

  const selectedCaption = captions[dayIndex % captions.length];

  return {
    quote: selectedQuote,
    caption: `Day ${dayIndex + 1}: ${selectedQuote} ${selectedCaption}`
  };
}

function buildDynamicDemoQuote(category, startIndex, excludeQuotes) {
  const subjects = dynamicQuoteSubjects[category] || dynamicQuoteSubjects.motivation;
  const excluded = new Set(excludeQuotes.map((quote) => quote.toLowerCase()));
  const totalCombinations = dynamicQuoteOpeners.length * subjects.length * dynamicQuoteEndings.length;

  for (let offset = 0; offset < totalCombinations; offset += 1) {
    const index = (startIndex + offset) % totalCombinations;
    const openerIndex = index % dynamicQuoteOpeners.length;
    const subjectIndex = Math.floor(index / dynamicQuoteOpeners.length) % subjects.length;
    const endingIndex = Math.floor(index / (dynamicQuoteOpeners.length * subjects.length)) % dynamicQuoteEndings.length;
    const quote = `${dynamicQuoteOpeners[openerIndex]} ${subjects[subjectIndex]} ${dynamicQuoteEndings[endingIndex]}.`;
    const wordCount = quote.trim().split(/\s+/).length;

    if (wordCount >= 8 && wordCount <= 18 && !excluded.has(quote.toLowerCase())) {
      return quote;
    }
  }

  throw new Error('Unable to create another unique demo quote for this generation request.');
}
